#!/usr/bin/env python3
"""Build the k=2 result tables (latency / energy / prefill placement / extras)
from the completed dag_A*.json ladder runs, and emit RESULTS_k2.md.

Definitions (documented in the README):
  arrival(req)  = summary.tiers[req.tier].start_s   (when the tier is released;
                  cross-checked against batch q_arrival_s, agrees within ~60 ms)
  prefill  (ms) = 1000 * (prefill_end_s - arrival)
  ttft     (ms) = 1000 * (first_token_s - arrival)
  decode   (ms) = 1000 * (end_s - first_token_s)
  e2e      (ms) = 1000 * (end_s - arrival)
Energy is phase/component tagged (by_event / by_class), NOT tier tagged.

    python3 make_results_tables.py   ->  RESULTS_k2.md
"""
import json, os, glob, collections

OUT = "/data2/chenyi9/KV-PIM/attacc_drampim_xinyao/output"
RUNGS = ["A1", "A2", "A3", "A3a", "A4", "A5", "A6"]
WL = [("star_repair", "star-repair"), ("pipeline_repair", "pipeline-repair"),
      ("multisource_rag", "multi-source RAG")]


def newest_complete(stem, k="k2"):
    """Directory with the most dag_*.json for this workload/k."""
    cands = glob.glob(f"{OUT}/*{stem}*_{k}")
    best, bn = None, -1
    for d in cands:
        n = len(glob.glob(f"{d}/dag_*.json"))
        if n > bn:
            best, bn = d, n
    return best, bn


def tkey(t):
    try:
        return (0, float(t))
    except ValueError:
        return (1, str(t))


def load(d, A):
    p = f"{d}/dag_{A}.json"
    return json.load(open(p)) if os.path.exists(p) else None


def per_request_latency(x):
    """rid -> (tier, prefill, decode, e2e, valid) in ms.
    valid=False when the run collapses the phases (A2 GPU-only baseline:
    prefill_end==end and first_token==0), so only e2e is comparable there."""
    S = x.get("summary", {})
    reqs, tiers = S.get("requests", {}), S.get("tiers", {})
    out = {}
    for rid, r in reqs.items():
        t = str(r.get("tier"))
        a = tiers.get(t, {}).get("start_s", 0.0)
        pe, ft, en = r["prefill_end_s"], r["first_token_s"], r["end_s"]
        valid = ft > 0 and pe <= ft <= en
        pf = 1000 * max(0.0, pe - a)
        dc = 1000 * max(0.0, en - ft)
        e2 = 1000 * max(0.0, en - a)
        out[rid] = (t, pf, dc, e2, valid)
    return out


def rung_phase_valid(latA):
    """A rung is phase-valid if most of its requests decompose cleanly."""
    v = [r[4] for r in latA.values()]
    return v and sum(v) >= 0.5 * len(v)


def energy_split(x):
    """Event names carry the phase: `decode*` are the decode pass, every other
    event (qkv, gpu_ff*, pim_kv_scan_*, gpu_prefill_*, KV placement) is the
    one-shot prefill pass. decode + prefill = total, no leftover bucket."""
    be = x.get("energy_breakdown_nj", {}).get("by_event", {})
    dc = sum(e for n, e in be.items() if n.lower().startswith("decode"))
    tot = sum(be.values())
    pf = tot - dc
    cls = x.get("energy_breakdown_nj", {}).get("by_class", {})
    return pf, dc, tot, cls


def fmt(v, nd=1):
    return f"{v:.{nd}f}" if isinstance(v, (int, float)) else str(v)


def main():
    md = []
    md.append("# k=2 ladder results (LLAMA3-8B, MQ PIM at 1.30 GHz)\n")
    md.append("Auto-generated by `make_results_tables.py` from the completed "
              "`dag_A*.json` ladder runs (7 rungs A1..A6 each). Re-run the "
              "script after more runs land; it picks the newest complete "
              "directory per workload. Metric definitions are in the appendix.\n")
    md.append("**Coverage (2026-08-28):** k=2 complete for star-repair, "
              "pipeline-repair, and multi-source RAG (below). map-reduce and "
              "debate at k=2, and every workload at k=8/k=32, are still running "
              "or queued.\n")

    # ---- cross-workload headline ----
    md.append("## 0. Headline: the ladder end to end\n")
    md.append("Makespan (s), total energy (kJ), and the share of prefill "
              "attention the rule sends to PIM, per rung.\n")
    head = collections.OrderedDict()
    dirs = {}
    for stem, name in WL:
        d, n = newest_complete(stem)
        dirs[stem] = d
        if n < 7:
            md.append(f"> {name}: only {n}/7 rungs, skipped.\n")
            continue
        row_m, row_e, row_p = [], [], []
        for A in RUNGS:
            x = load(d, A)
            if not x:
                row_m.append("-"); row_e.append("-"); row_p.append("-"); continue
            row_m.append(x["makespan_s"])
            row_e.append(x["energy_nj"] / 1e12)  # kJ
            sides = x.get("prefill_attention_sides") or {}
            npim = sum(1 for v in sides.values() if v == "pim")
            row_p.append(f"{100*npim/len(sides):.0f}%" if sides else "0%")
        head[name] = (row_m, row_e, row_p)

    def block(title, idx, nd):
        md.append(f"\n**{title}**\n")
        md.append("| workload | " + " | ".join(RUNGS) + " |")
        md.append("|" + "---|" * (len(RUNGS) + 1))
        for name, (m, e, p) in head.items():
            vals = [m, e, p][idx]
            cells = [fmt(v, nd) if isinstance(v, (int, float)) else str(v) for v in vals]
            md.append(f"| {name} | " + " | ".join(cells) + " |")
    block("Makespan (s)", 0, 2)
    block("Total energy (kJ)", 1, 1)
    block("Prefill attention on PIM (share of agents)", 2, 0)

    # speedups
    md.append("\n**Speedup of A6 over A1 (dense no-reuse) and A2 (GPU-only)**\n")
    md.append("| workload | A6 vs A1 | A6 vs A2 | energy A6 vs A1 |")
    md.append("|---|---|---|---|")
    for name, (m, e, p) in head.items():
        if m[0] in ("-",) or m[-1] in ("-",):
            continue
        md.append(f"| {name} | {m[0]/m[-1]:.1f}x | {m[1]/m[-1]:.1f}x | "
                  f"{e[0]/e[-1]:.0f}x |")

    # ---- observations (data-driven) ----
    md.append("\n## 1. Observations worth a second look\n")
    obs = []
    for name, (m, e, p) in head.items():
        if "-" in m:
            continue
        A1, A2, A3, A3a, A4, A5, A6 = m
        # A1 vs A2 flip
        if A1 > A2:
            obs.append(f"- **{name}**: the dense no-reuse reference A1 is "
                       f"{A1/A2:.1f}x *slower* than GPU-only A2 "
                       f"({A1:.1f}s vs {A2:.1f}s), because decode in banks over a "
                       f"dense per-request KV copy pays for KV that is never shared.")
        else:
            obs.append(f"- **{name}**: GPU-only A2 is {A2/A1:.1f}x *slower* than "
                       f"the A1 reference ({A2:.1f}s vs {A1:.1f}s): moving the KV "
                       f"over the link every turn costs more than AttAcc's in-bank "
                       f"decode.")
        # A3 anomaly: banks over naive layout vs A2
        if A3 >= A2:
            obs.append(f"  - A3 (decode in banks over the append-order layout) is "
                       f"{A3:.1f}s, *no better* than A2 ({A2:.1f}s); the win only "
                       f"appears at A3a ({A3a:.1f}s) and A4 ({A4:.1f}s), where the "
                       f"write-mask and the split-channel layout remove the "
                       f"irregular access. This is the paper's Problem 1 in the data.")
        # A5 vs A6
        eA5, eA6 = e[5], e[6]
        pA5, pA6 = p[5], p[6]
        if abs(A5 - A6) < 0.05 and abs(eA5 - eA6) / eA5 < 0.02:
            obs.append(f"  - A6 (dynamic rule) matches A5 (all-PIM) at "
                       f"{A6:.1f}s, sending {pA6} of prefills to PIM; the rule "
                       f"agrees with all-PIM for this workload.")
        else:
            obs.append(f"  - A6 (dynamic) sends only {pA6} of prefills to PIM vs "
                       f"A5's {pA5}, and still ends at {A6:.1f}s "
                       f"({(1-A6/A5)*100:+.0f}% makespan, "
                       f"{(1-eA6/eA5)*100:+.0f}% energy vs A5): the rule pulls the "
                       f"prefills that are cheaper on the GPU back off the banks.")
    md += obs

    # ---- per workload ----
    for stem, name in WL:
        d = dirs[stem]
        if not d or len(glob.glob(f"{d}/dag_*.json")) < 7:
            continue
        md.append(f"\n---\n\n## {name}\n")
        md.append(f"`{os.path.basename(d)}`\n")

        lat = {A: per_request_latency(load(d, A)) for A in RUNGS}
        # tier order from workload.tiers
        wl = load(d, "A6")["workload"]["tiers"]
        tiers = sorted(wl.keys(), key=tkey)

        # ---- Table 1: latency per tier x rung (prefill / decode / e2e) ----
        # prefill & decode need a clean phase split, so A2 (collapsed) is n/a;
        # e2e = end - arrival is valid for every rung.
        valid = {A: rung_phase_valid(lat[A]) for A in RUNGS}
        for phase, pi, needsplit in [("prefill", 1, True), ("decode", 2, True),
                                     ("e2e", 3, False)]:
            md.append(f"\n**Latency [{phase}] (ms), tier x rung** "
                      f"(mean over the tier's agents)\n")
            md.append("| tier | " + " | ".join(RUNGS) + " |")
            md.append("|" + "---|" * (len(RUNGS) + 1))
            for t in tiers:
                cells = []
                for A in RUNGS:
                    if needsplit and not valid[A]:
                        cells.append("n/a"); continue
                    vals = [v[pi] for v in lat[A].values() if v[0] == t]
                    cells.append(f"{sum(vals)/len(vals):.1f}" if vals else "-")
                md.append(f"| {t} | " + " | ".join(cells) + " |")
            cells = []
            for A in RUNGS:
                if needsplit and not valid[A]:
                    cells.append("n/a"); continue
                vals = [v[pi] for v in lat[A].values()]
                cells.append(f"{sum(vals)/len(vals):.1f}" if vals else "-")
            md.append(f"| **mean** | " + " | ".join(cells) + " |")
        md.append("\n> A2 is the GPU-only software baseline; this sim path "
                  "collapses prefill and decode into one timestamp "
                  "(`prefill_end==end`, `first_token=0`), so its prefill/decode "
                  "are `n/a` and only e2e is comparable.\n")

        # ---- Table 2: energy per rung, prefill/decode/other + class ----
        md.append(f"\n**Energy (mJ) per rung** "
                  f"(prefill/decode by event phase; GPU/PIM/LINK by unit; "
                  f"not tier-resolved)\n")
        md.append("| rung | prefill | decode | total | GPU | PIM | LINK | DIE |")
        md.append("|---|---|---|---|---|---|---|---|")
        for A in RUNGS:
            x = load(d, A)
            pf, dc, tot, cls = energy_split(x)
            g = cls.get("GPU", 0)/1e6; pm = cls.get("PIM", 0)/1e6
            lk = cls.get("LINK", 0)/1e6; di = cls.get("DIE", 0)/1e6
            md.append(f"| {A} | {pf/1e6:.1f} | {dc/1e6:.1f} | {tot/1e6:.1f} | "
                      f"{g:.1f} | {pm:.1f} | {lk:.2f} | {di:.4f} |")

        # ---- Table 3: GPU/PIM prefill placement per tier per agent (A5, A6) ----
        md.append(f"\n**Prefill placement, per tier, each agent one point "
                  f"(A5 static-all-PIM, A6 dynamic rule)**\n")
        md.append("| tier | agents | A5 PIM | A5 GPU | A6 PIM | A6 GPU | A6 PIM% |")
        md.append("|---|---|---|---|---|---|---|")
        q2t = {}
        for t, qs in wl.items():
            for q in qs:
                q2t[q] = t
        for A in ("A5", "A6"):
            pass
        s5 = load(d, "A5").get("prefill_attention_sides") or {}
        s6 = load(d, "A6").get("prefill_attention_sides") or {}
        per_tier = collections.defaultdict(lambda: [0, 0, 0, 0, 0])  # n, p5,g5,p6,g6
        for q, t in q2t.items():
            per_tier[t][0] += 1
            per_tier[t][1] += (s5.get(q) == "pim")
            per_tier[t][2] += (s5.get(q, "gpu") != "pim")
            per_tier[t][3] += (s6.get(q) == "pim")
            per_tier[t][4] += (s6.get(q, "gpu") != "pim")
        tot = [0, 0, 0, 0, 0]
        for t in sorted(per_tier.keys(), key=tkey):
            n, p5, g5, p6, g6 = per_tier[t]
            for i, v in enumerate((n, p5, g5, p6, g6)):
                tot[i] += v
            md.append(f"| {t} | {n} | {p5} | {g5} | {p6} | {g6} | "
                      f"{100*p6/n:.0f}% |")
        n, p5, g5, p6, g6 = tot
        md.append(f"| **all** | {n} | {p5} | {g5} | {p6} | {g6} | {100*p6/n:.0f}% |")

        # ---- Table 4: extras ----
        md.append(f"\n**Extras**\n")
        md.append("| rung | makespan s | KV over link (GiB) | prefill rows GPU | "
                  "prefill rows PIM | decode | kv layout |")
        md.append("|---|---|---|---|---|---|---|")
        for A in RUNGS:
            x = load(d, A)
            rows = x.get("prefill_attention_rows", {})
            md.append(f"| {A} | {x['makespan_s']:.2f} | "
                      f"{x.get('link_bytes',0)/2**30:.2f} | "
                      f"{rows.get('gpu','-')} | {rows.get('pim','-')} | "
                      f"{x.get('decode_attn','-')} | {x.get('kv_mapping','-')} |")

    # ---- appendix ----
    md.append("\n---\n\n## Appendix: definitions & rung legend\n")
    md.append("- **arrival(req)** = start of its tier "
              "(`summary.tiers[tier].start_s`, cross-checked against batch "
              "`q_arrival_s`); prefill and e2e are measured from it, so they "
              "exclude the wait for upstream tiers. "
              "prefill = `prefill_end_s - arrival`, "
              "decode = `end_s - first_token_s`, e2e = `end_s - arrival`.\n")
    md.append("- Energy `by_event` names carry the phase: events starting "
              "`decode` are the decode pass, all others (qkv, gpu_ff*, "
              "pim_kv_scan_*, gpu_prefill_*, KV placement) are the one-shot "
              "prefill pass, so prefill + decode = total. `by_class` splits the "
              "same total by unit (GPU/PIM/LINK/DIE/TLB). Neither carries a tier "
              "tag, so the energy table is per rung only.\n")
    md.append("- The **KV over link** column in Extras is the headline of the "
              "in-memory story: A2 (GPU-only) streams the whole KV every turn, "
              "the PIM rungs keep it in the banks.\n")
    md.append("- Rungs: **A1** AttAcc dense no-reuse (decode in banks, prefill GPU); "
              "**A2** GPU-only software reuse; **A3** decode in banks over the "
              "append-order layout; **A3a** + write-mask; **A4** + split-channel "
              "master-diff layout; **A5** + all prefill in banks; **A6** + dynamic "
              "per-prefill placement rule.\n")

    path = f"{OUT}/analysis/RESULTS_k2.md"
    open(path, "w").write("\n".join(md) + "\n")
    print("wrote", path, f"({len(md)} lines)")


if __name__ == "__main__":
    main()
